Create task DEMO.DEMO_SCHEMA.WEATHERTASK 
WAREHOUSE = COMPUTE_WH
SCHEDULE = 'USING CRON 34 8 * * * UTC'
AS 
COPY INTO DEMO.DEMO_SCHEMA.WEATHER
FROM 
(
SELECT 
--t.$1,
t.$1:city.findname,
t.$1:city.coord.lat,
t.$1:city.coord.lon,
--t.$1:country.findname
t.$1:clouds.all,
t.$1:main.humidity,
t.$1:main.pressure,
t.$1:main.temp,
t.$1:MAIN.TIME,
t.$1:WEATHER[0]:MAIN
FROM @DEMO.demo_schema.WEATHER_STAGE T);

ALTER TASK DEMO.DEMO_SCHEMA.WEATHERTASK SUSPEND;

SHOW TASKS;

SELECT *
FROM TABLE (INFORMATION_SCHEMA.TASK_HISTORY())
ORDER BY SCHEDULED_TIME;


